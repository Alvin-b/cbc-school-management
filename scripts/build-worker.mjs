#!/usr/bin/env node
/**
 * Bundles the Cloudflare Worker (auth + REST API) into a single ES module.
 * Everything is bundled locally: no external imports at runtime.
 */
import { build } from 'esbuild';
import { mkdirSync } from 'node:fs';

mkdirSync('dist-worker', { recursive: true });

const result = await build({
  entryPoints: ['worker/src/index.js'],
  outfile: 'dist-worker/index.js',
  bundle: true,
  format: 'esm',
  target: 'es2022',
  platform: 'browser',
  conditions: ['workerd', 'worker', 'browser'],
  // The D1 schema is imported as a raw string (worker/schema.sql).
  loader: { '.sql': 'text' },
  minify: false,
  sourcemap: false,
  logLevel: 'info',
  banner: {
    js: '// ElimuTrack worker bundle — generated by scripts/build-worker.mjs',
  },
});

if (result.errors.length) process.exit(1);
console.log('worker bundle written to dist-worker/index.js');
